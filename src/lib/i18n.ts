type Lang = 'it' | 'en';
let lang: Lang = (localStorage.getItem('lang') as Lang) || 'it';
const listeners = new Set<() => void>();

export function setLang(l: Lang) { lang = l; localStorage.setItem('lang', l); document.documentElement.lang = l; listeners.forEach((f) => f()); }
export function getLang() { return lang; }
export function t(s: string) { return lang === 'en' ? EN[s] ?? s : s; }
/** Traduce una frase con segnaposto: tf('Rimuovere {nome} dal viaggio?', { nome: 'Luca' }). */
export function tf(s: string, vars: Record<string, string | number>) {
  return t(s).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}
/** I messaggi dell'attività sono salvati in italiano: in inglese traduciamo l'inizio della frase. */
const ACTIVITY_EN: [RegExp, string][] = [
  [/^ha creato il viaggio/, 'created the trip'], [/^si è unito al viaggio/, 'joined the trip'],
  [/^ha caricato /, 'uploaded '], [/^ha aggiunto /, 'added '], [/^ha segnato pagato: /, 'marked as paid: '],
];
export function activityText(s: string) {
  if (lang !== 'en') return s;
  for (const [re, en] of ACTIVITY_EN) if (re.test(s)) return s.replace(re, en);
  return s;
}

export function useLang() {
  return useSyncExternalStore((cb) => { listeners.add(cb); return () => listeners.delete(cb); }, () => lang);
}
